# Writes the header with the build's time in UTC (ISO 8601), for the BuildTimeUtc string of Versioninfo.rc; the in-game
# update check compares it with the release asset's time. Runs before every build (premake5.lua) but only writes a new
# time when the build will link: the header or -Target is missing, or a file of the inputs (the remaining arguments,
# files or folders) is newer than -Target. A build without changes then doesn't compile the resource and link again.
# The file is written under a temporary name and moved into place.
param([Parameter(Mandatory = $true)][string]$Out, [string]$Target, [Parameter(ValueFromRemainingArguments = $true)][string[]]$Inputs)

# Relative paths are relative to the folder the script runs in
[IO.Directory]::SetCurrentDirectory((Get-Location).Path)

if ($Target -and (Test-Path $Out) -and (Test-Path $Target))
{
    $built = [IO.File]::GetLastWriteTimeUtc((Resolve-Path $Target))
    $changed = $false
    foreach ($in in $Inputs)
    {
        if ([IO.Directory]::Exists($in)) { $files = [IO.Directory]::EnumerateFiles((Resolve-Path $in), "*", [IO.SearchOption]::AllDirectories) }
        elseif ([IO.File]::Exists($in)) { $files = @((Resolve-Path $in).Path) }
        else { continue }
        foreach ($f in $files) { if ([IO.File]::GetLastWriteTimeUtc($f) -gt $built) { $changed = $true; break } }
        if ($changed) { break }
    }
    if (-not $changed) { exit 0 }
}

$time = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Out) | Out-Null
$temp = "$Out.$PID.tmp"
Set-Content -Path $temp -Encoding ascii -Value @(
    "// Generated by tools/buildtime.ps1",
    "#define rsc_BuildTimeUtc `"$time`""
)
try { Move-Item -Force -Path $temp -Destination $Out -ErrorAction Stop }
catch { Remove-Item -Force -ErrorAction SilentlyContinue $temp; if (-not (Test-Path $Out)) { throw } }
exit 0
