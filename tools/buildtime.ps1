# Writes the header with the build's time in UTC (ISO 8601), for the BuildTimeUtc string of Versioninfo.rc. Runs before
# every build (premake5.lua), so every build, local or CI, carries its own time; the in-game update check compares it
# with the release asset's time. Projects built in parallel may run it at the same moment: the file is written under a
# temporary name and moved into place, and a project that loses the race keeps the other's (same) time.
param([Parameter(Mandatory = $true)][string]$Out)
$time = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Out) | Out-Null
$temp = "$Out.$PID.tmp"
Set-Content -Path $temp -Encoding ascii -Value @(
    "// Generated by tools/buildtime.ps1 before each build",
    "#define rsc_BuildTimeUtc `"$time`""
)
try { Move-Item -Force -Path $temp -Destination $Out -ErrorAction Stop }
catch { Remove-Item -Force -ErrorAction SilentlyContinue $temp; if (-not (Test-Path $Out)) { throw } }
exit 0
